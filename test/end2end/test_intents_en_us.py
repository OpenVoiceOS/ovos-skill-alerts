    def _remove_list(self, list_name: str):
        """Complete a seeded list and its items, so later tests that resolve
        a list by name do not see it."""
        from ovos_skill_alerts.util import AlertType

        skill = self.minicroft.plugin_skills[SKILL_ID].instance
        for parent in skill._get_alerts_list(AlertType.TODO, name=list_name):
            for child in skill.alert_manager.get_children(parent.ident):
                skill.alert_manager.mark_todo_complete(child)
            skill.alert_manager.mark_todo_complete(parent)

    def _seed_list_with_item(self, list_name: str, item_name: str):
        """Create a TODO list (if needed) and add one child item to it
        directly via the AlertManager API, bypassing the interactive
        get_response cascade that add_list_subitems' real intent handler uses
        (there is no scripted answer to feed it in this end2end harness).

        This exists because delete_list/delete_list_entries's own
        `_resolve_requested_alert` filters candidate TODO lists down to
        ones that HAVE CHILDREN (`filter(lambda alert: alert.children,
        alerts)`) whenever the utterance's vocab includes "list" -- an
        empty list is invisible to both intents and the handler silently
        returns without speaking. Each caller must give its list a unique
        name so parallel/sequential tests against the shared module
        MiniCroft don't consume each other's single item.

        The parent list itself is created directly via the AlertManager
        API (like the child below) rather than by firing create_list as an
        intent -- create_list moved from Adapt to a padacioso .intent file,
        so there is no adapt-only pipeline left to seed it through, and
        this fixture only needs the list to exist, not to exercise the
        create_list intent handler itself.
        """
        from ovos_skill_alerts.util import AlertType
        from ovos_skill_alerts.util.alert import Alert, DAVType

        skill = self.minicroft.plugin_skills[SKILL_ID].instance
        parents = skill._get_alerts_list(AlertType.TODO, name=list_name)
        if not parents:
            parent = Alert.create(
                alert_name=list_name,
                alert_type=AlertType.TODO,
                dav_type=DAVType.VTODO,
                lang=LANG,
            )
            skill.alert_manager.add_alert(parent)
            parents = skill._get_alerts_list(AlertType.TODO, name=list_name)
        assert parents, f"failed to create/find TODO list {list_name!r}"
        parent = parents[0]
        child = Alert.create(
            alert_name=item_name,
            alert_type=AlertType.TODO,
            context=dict(related_to=parent.ident),
            lang=LANG,
        )
        skill.alert_manager.add_alert(child)

