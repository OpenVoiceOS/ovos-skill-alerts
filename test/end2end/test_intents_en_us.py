def _m2v_stage(pipeline_id):
    """Map the normalized ``pipeline_id`` off ``ovos.intent.matched`` to the
    m2v stage name it names -- "classifier" for the trained checkpoint,
    "prototype" for the per-boot template stage, or the raw id/None for
    anything else (a different pipeline plugin matched, or nothing did).
    """
    return {
        "ovos-m2v-pipeline": "classifier",
        "ovos-m2v-prototype-pipeline": "prototype",
    }.get(pipeline_id, pipeline_id or "unmatched")


class _IntentRoutingMixin:
    """Shared MiniCroft setup."""

    @classmethod
    def setUpClass(cls):
        cls.minicroft = _MODULE_MINICROFT

    @classmethod
    def tearDownClass(cls):
        pass

    def _fire(self, utterance: str, session_prefix: str = "e2e-en_us"):
        """Fire *utterance* through the m2v dual pipeline and return the
        captured bus messages.
        """
        session = Session(f"{session_prefix}-{hash(utterance)}")
        session.lang = LANG
        session.pipeline = M2V_DUAL_PIPELINE
        message = Message(
            "recognizer_loop:utterance",
            {"utterances": [utterance], "lang": LANG},
            {"session": session.serialize()},
        )
        capture = CaptureSession(self.minicroft)
        capture.capture(message, timeout=30)
        return capture.finish()

    def _assert_intent(self, utterance: str, intent_file: str):
        """Fire an utterance and assert on a SUBSET of the resulting bus
        traffic: the intent matched, plus at least one visible side effect
        (speak / GUI / audio cue / a follow-up question via get_response).

        This deliberately does NOT assert a literal, fully-ordered
        ``expected_messages`` sequence. ovos-skill-alerts' handlers commonly
        ask a clarifying follow-up question (``get_response``) for
        under-specified utterances (e.g. "set an alarm" with no time), which
        produces a different, still-correct, message sequence than a fully
        resolved one-shot command. Asserting the literal sequence made most
        of this suite fail/flap on real (correct) skill behavior. See the
        ovos-skill-personal PR #113 wire-name/sequence-drift discussion for
        the same pattern in another skill.
        """
        intent_name = intent_file[:-len(".intent")] if intent_file.endswith(".intent") else intent_file
        intent_msg_type = f"{SKILL_ID}:{intent_name}"
        messages = self._fire(utterance)
        types = [m.msg_type for m in messages]
        matched = [m for m in messages if m.msg_type == "ovos.intent.matched"]
        observed = matched[0].data.get("intent_name") if matched else None
        stage = _m2v_stage(matched[0].data.get("pipeline_id")) if matched else "unmatched"
        self.assertIn(
            intent_msg_type, types,
            f"{utterance!r}: expected {intent_msg_type!r}, observed "
            f"{observed!r} (m2v stage: {stage}) -- full bus trace: {types!r}")
        side_effects = ("speak", "gui.", "mycroft.audio.play_sound",
                        "skill.converse.get_response")
        self.assertTrue(
            any(any(se in t for se in side_effects) for t in types),
            f"no visible side effect for {utterance!r} -> {types}",
        )

    def _assert_intent_with_dialog_data(self, utterance: str, intent_file: str,
                                        dialog_key: str, expected_value: str):
        """Like ``_assert_intent``, but also asserts on the CONTENT of the
        spoken ``ovos.utterance.speak`` dialog data, not just that some side
        effect occurred -- proves the matched slot value actually reached the
        spoken confirmation, not just that routing landed on the right
        intent name.
        """
        intent_name = intent_file[:-len(".intent")] if intent_file.endswith(".intent") else intent_file
        intent_msg_type = f"{SKILL_ID}:{intent_name}"
        messages = self._fire(utterance, session_prefix="e2e-en_us-dialog")
        types = [m.msg_type for m in messages]
        matched = [m for m in messages if m.msg_type == "ovos.intent.matched"]
        observed = matched[0].data.get("intent_name") if matched else None
        stage = _m2v_stage(matched[0].data.get("pipeline_id")) if matched else "unmatched"
        self.assertIn(
            intent_msg_type, types,
            f"{utterance!r}: expected {intent_msg_type!r}, observed "
            f"{observed!r} (m2v stage: {stage}) -- full bus trace: {types!r}")
        speaks = [m for m in messages if m.msg_type == "ovos.utterance.speak"]
        self.assertTrue(speaks, f"no ovos.utterance.speak for {utterance!r} -> {types}")
        dialog_data = speaks[0].data.get("meta", {}).get("data", {})
        self.assertEqual(
            dialog_data.get(dialog_key), expected_value,
            f"spoken dialog data {dialog_key!r} was {dialog_data.get(dialog_key)!r}, "
            f"expected {expected_value!r} -- full dialog data: {dialog_data!r}")

    def _assert_intent_any(self, utterance: str, intent_files: list):
        """Like ``_assert_intent``, but accepts any one of several sibling
        intent files as a pass -- ONLY legitimate when every name given
        resolves to the literal same handler callable in the running skill
        (two intent names, one handler), which this method verifies
        structurally via ``skill._intent_handlers`` before doing anything
        else, so a future caller can't misuse this to paper over a
        genuinely wrong sibling intent that happens to share a name.

        For a phrasing whose winner flips between such siblings depending on
        the matching engine's own tie-break behavior, only the wire intent
        NAME differs between winners, not skill behavior -- pinning to one
        exact name makes the row flaky for a distinction that carries no
        functional difference. This still pins the intent that actually
        won to the one shared handler, via the OVOS-PIPELINE-1 §8.1
        ``ovos.intent.handler.start`` orchestrator-emitted spec event
        (SpecMessage.INTENT_HANDLER_START, payload
        ``{"skill_id", "intent_name"}``) -- deliberately NOT any
        ``mycroft.skill.handler.*`` event, which is an internal
        workshop<->core wrapper signal outside the spec that is due to be
        removed.
        """
        intent_names = [f[:-len(".intent")] if f.endswith(".intent") else f
                        for f in intent_files]
        skill = self.minicroft.plugin_skills[SKILL_ID].instance
        handlers = {n: skill._intent_handlers.get(n) for n in intent_names}
        missing = [n for n, h in handlers.items() if h is None]
        self.assertFalse(
            missing, f"no registered handler for intent(s) {missing!r} -- "
                     f"known: {sorted(skill._intent_handlers)!r}")
        distinct = {h.__func__ if hasattr(h, "__func__") else h
                    for h in handlers.values()}
        self.assertEqual(
            len(distinct), 1,
            f"_assert_intent_any is only valid across siblings bound to "
            f"the SAME handler; {dict(handlers)!r} resolve to {len(distinct)} "
            f"distinct handlers")

        intent_msg_types = {f"{SKILL_ID}:{n}" for n in intent_names}
        messages = self._fire(utterance)
        types = [m.msg_type for m in messages]
        matched = [m for m in messages if m.msg_type == "ovos.intent.matched"]
        observed = matched[0].data.get("intent_name") if matched else None
        stage = _m2v_stage(matched[0].data.get("pipeline_id")) if matched else "unmatched"
        self.assertTrue(
            intent_msg_types.intersection(types),
            f"{utterance!r}: expected one of {intent_msg_types!r}, observed "
            f"{observed!r} (m2v stage: {stage}) -- full bus trace: {types!r}")

        starts = [m for m in messages if m.msg_type == "ovos.intent.handler.start"]
        self.assertTrue(
            starts, f"no 'ovos.intent.handler.start' in {types!r}")
        observed_names = {m.data.get("intent_name") for m in starts
                          if m.data.get("skill_id") == SKILL_ID}
        self.assertTrue(
            observed_names & set(intent_names),
            f"'ovos.intent.handler.start' fired {SKILL_ID!r} intent_name(s) "
            f"{observed_names!r}, expected one of {intent_names!r} "
            f"(any sibling of the shared handler)")

    def _seed_list_with_item(self, list_name: str, item_name: str):
        """Create a TODO list (if needed) and add one child item to it
        directly via the AlertManager API, bypassing the interactive
        get_response cascade that AddListSubitems' real intent handler uses
        (there is no scripted answer to feed it in this end2end harness).

        This exists because DeleteList/DeleteListEntries's own
        `_resolve_requested_alert` filters candidate TODO lists down to
        ones that HAVE CHILDREN (`filter(lambda alert: alert.children,
        alerts)`) whenever the utterance's vocab includes "list" -- an
        empty list is invisible to both intents and the handler silently
        returns without speaking. Each caller must give its list a unique
        name so parallel/sequential tests against the shared module
        MiniCroft don't consume each other's single item.

        The parent list itself is created directly via the AlertManager API
        (like the child below) rather than by firing CreateList as an
        intent -- this fixture only needs the list to exist, not to
        exercise the CreateList intent handler itself.
        """
        from ovos_skill_alerts.util import AlertType
        from ovos_skill_alerts.util.alert import Alert, DAVType

        skill = self.minicroft.plugin_skills[SKILL_ID].instance
        parents = skill._get_alerts_list(AlertType.TODO, name=list_name)
        if not parents:
            parent = Alert.create(
                alert_name=list_name,
                alert_type=AlertType.TODO,
                dav_type=DAVType.VTODO,
                lang=LANG,
            )
            skill.alert_manager.add_alert(parent)
            parents = skill._get_alerts_list(AlertType.TODO, name=list_name)
        assert parents, f"failed to create/find TODO list {list_name!r}"
        parent = parents[0]
        child = Alert.create(
            alert_name=item_name,
            alert_type=AlertType.TODO,
            context=dict(related_to=parent.ident),
            lang=LANG,
        )
        skill.alert_manager.add_alert(child)


