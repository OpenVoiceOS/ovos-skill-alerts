# A single MiniCroft is booted once for the whole module and shared across
# every TestCase below. Booting one per class (the original generated
# pattern) meant ~30 separate MiniCroft boots per CI run, which is what made
# this suite time out / get killed in CI even with parallel workers disabled.
_MODULE_MINICROFT = None

# The skill persists its alert/todo-list store (alerts.json) under the
# process's XDG data dir, keyed only by skill_id -- NOT per test run. Left
# alone, that file lives at a machine-global path
# (~/.local/share/mycroft/filesystem/skills/<skill_id>/alerts.json) and
# accumulates indefinitely across every local run and every CI job that
# doesn't already isolate HOME/XDG_DATA_HOME, making any test whose
# behavior depends on "does this alert/list already exist" nondeterministic
# (see the delete_list/delete_list_entries xfails below, and issue #138's
# state-leak investigation). Point XDG_DATA_HOME at a fresh tmpdir for the
# whole module run so every invocation of this file starts from a
# genuinely empty store, regardless of what accumulated on disk from any
# other process.
_ISOLATED_XDG_DATA_HOME = None
_ORIGINAL_XDG_DATA_HOME = None


def setUpModule():
    global _MODULE_MINICROFT, _ISOLATED_XDG_DATA_HOME, _ORIGINAL_XDG_DATA_HOME
    _ORIGINAL_XDG_DATA_HOME = os.environ.get("XDG_DATA_HOME")
    _ISOLATED_XDG_DATA_HOME = tempfile.mkdtemp(prefix="ovos-skill-alerts-test-xdg-")
    os.environ["XDG_DATA_HOME"] = _ISOLATED_XDG_DATA_HOME
    _MODULE_MINICROFT = get_minicroft([SKILL_ID],
                                      default_pipeline=PADACIOSO_TEST_PIPELINE,
                                      wait_for_trained=False)
    # See end2end._wait_trained for why this wait (not a fixed sleep) is
    # needed before the first real test can safely fire a query.
    wait_for_minicroft_ready(_MODULE_MINICROFT)


def tearDownModule():
    global _MODULE_MINICROFT, _ISOLATED_XDG_DATA_HOME, _ORIGINAL_XDG_DATA_HOME
    if _MODULE_MINICROFT is not None:
        _MODULE_MINICROFT.stop()
        _MODULE_MINICROFT = None
    if _ORIGINAL_XDG_DATA_HOME is None:
        os.environ.pop("XDG_DATA_HOME", None)
    else:
        os.environ["XDG_DATA_HOME"] = _ORIGINAL_XDG_DATA_HOME
    if _ISOLATED_XDG_DATA_HOME is not None:
        shutil.rmtree(_ISOLATED_XDG_DATA_HOME, ignore_errors=True)
        _ISOLATED_XDG_DATA_HOME = None


class _IntentRoutingMixin:
    """Shared MiniCroft setup."""

    @classmethod
    def setUpClass(cls):
        cls.minicroft = _MODULE_MINICROFT

